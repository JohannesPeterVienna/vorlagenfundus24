// Interaktionstest: Länderwechsel, Fristen, .docx-Export, Druckansicht, Kuvertprüfung. Start: node tests/interaktion.js <ausgabeordner>
const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const { server } = require('./server');
const assert = require('assert');
(async () => {
  const out = process.argv[2] || '.';
  const srv = await server(0); const port = srv.address().port;
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const page = await browser.newPage({ acceptDownloads: true, viewport: { width: 1366, height: 900 } });
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.route(/googlesyndication|googletagmanager/, r => r.abort());
  await page.goto(`http://127.0.0.1:${port}/wohnung-kuendigen/`, { waitUntil: 'networkidle' });
  await page.check('input[name=land][value=DE]');
  await page.fill('#b-miete-kuendigung-zugang', '2026-11-04');
  await page.fill('#b-miete-kuendigung-objekt', 'Musterstraße 1, 10115 Berlin');
  await page.fill('#b-miete-kuendigung-abs_name', 'Erika Muster');
  const frist = await page.textContent('.fristkarte');
  assert(frist.includes('31. Januar 2027'), 'DE-Termin fehlt: ' + frist);
  await page.check('input[name=land][value=CH]');
  const brief = (await page.textContent('.blatt')).split('Musterstraße').join('');
  assert(!brief.includes('ß'), 'CH-Brief enthält ß: ' + brief.slice(Math.max(0, brief.indexOf('ß') - 80), brief.indexOf('ß') + 20));
  assert(brief.includes('Freundliche Grüsse'));
  assert((await page.textContent('.blatt')).includes('Wohnung Musterstraße 1'), 'Nutzereingabe verändert');
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('text=Als Word-Datei (.docx)')]);
  await dl.saveAs(out + '/test.docx');
  await page.emulateMedia({ media: 'print' });
  await page.evaluate(() => { document.body.classList.add('druck-brief'); const b = document.querySelector('.blatt').cloneNode(true); const d = document.createElement('div'); d.className = 'druckbereich'; b.style.transform = 'none'; d.appendChild(b); document.body.appendChild(d); });
  await page.pdf({ path: out + '/test.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: 'screen' });
  await page.goto(`http://127.0.0.1:${port}/oenorm-a-1080-din-5008/`, { waitUntil: 'networkidle' });
  assert((await page.textContent('.wz-ausgabe')).includes('Passt'));
  await page.goto(`http://127.0.0.1:${port}/kuendigungsfristen-wohnung-vergleich/`, { waitUntil: 'networkidle' });
  await page.fill('#fv-zugang', '2026-11-05');
  const v = await page.textContent('.vergleich');
  assert(v.includes('28. Februar 2027') && v.includes('31. Dezember 2026') && v.includes('31. März 2027'), v);
  assert(!errs.length, errs.join('|'));
  console.log('Interaktionstest bestanden.');
  await browser.close(); srv.close();
})().catch(e => { console.error(e.message); process.exit(1); });
