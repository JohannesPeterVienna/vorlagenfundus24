// Interaktionstest: Länderwechsel, Fristen, .docx-Export, Druckansicht, Kuvertprüfung. Start: node tests/interaktion.js <ausgabeordner>
const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const { server } = require('./server');
const assert = require('assert');
(async () => {
  const out = process.argv[2] || '.';
  const srv = await server(0); const port = srv.address().port;
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
  const page = await browser.newPage({ acceptDownloads: true, viewport: { width: 1366, height: 900 } });
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.route(/googlesyndication|googletagmanager/, r => r.abort());
  await page.goto(`http://127.0.0.1:${port}/wohnung-kuendigen/`, { waitUntil: 'networkidle' });
  await page.check('input[name=land][value=DE]');
  await page.fill('#b-miete-kuendigung-datum', '2026-11-03');   // fester Tag: Zugang liegt nicht vor dem Datum des Schreibens
  await page.fill('#b-miete-kuendigung-zugang', '2026-11-04');
  await page.fill('#b-miete-kuendigung-objekt', 'Musterstraße 1, 10115 Berlin');
  await page.fill('#b-miete-kuendigung-abs_name', 'Erika Muster');
  const frist = await page.textContent('.fristkarte');
  assert(frist.includes('31. Januar 2027'), 'DE-Termin fehlt: ' + frist);
  await page.check('input[name=land][value=CH]');
  const brief = (await page.textContent('.blatt')).split('Musterstraße').join('');
  assert(!brief.includes('ß'), 'CH-Brief enthält ß: ' + brief.slice(Math.max(0, brief.indexOf('ß') - 80), brief.indexOf('ß') + 20));
  assert(brief.includes('Freundliche Grüsse'));
  assert((await page.textContent('.blatt')).includes('Wohnung Musterstraße 1'), 'Nutzereingabe verändert');
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('text=Als Word-Datei (.docx)')]);
  await dl.saveAs(out + '/test.docx');
  // AT befristet, erstes Jahr läuft: Sperrhinweis in Vorschau, Versand und .docx (gleiche Regeln)
  await page.check('input[name=land][value=AT]');
  await page.selectOption('#b-miete-kuendigung-variante_AT', 'befristet');
  await page.fill('#b-miete-kuendigung-mietbeginn', '2026-01-01');
  await page.fill('#b-miete-kuendigung-datum', '2026-10-28');   // Zugang darf nicht vor dem Datum des Schreibens liegen
  await page.fill('#b-miete-kuendigung-zugang', '2026-10-31');
  const at = await page.textContent('.blatt');
  assert(at.includes('ENTWURF – erst ab 1. Jänner 2027 verwendbar') && !at.includes('abgelaufen'), at.slice(0, 400));
  assert((await page.textContent('.versand')).includes('ENTWURF'));
  const [dl2] = await Promise.all([page.waitForEvent('download'), page.click('text=Als Word-Datei (.docx)')]);
  await dl2.saveAs(out + '/test-at.docx');
  assert(require('fs').readFileSync(out + '/test-at.docx').toString('utf8').includes('ENTWURF – erst ab'), 'docx ohne Sperrhinweis');
  await page.selectOption('#b-miete-kuendigung-variante_AT', 'unbefristet-monatlich');
  await page.emulateMedia({ media: 'print' });
  await page.evaluate(() => { document.body.classList.add('druck-brief'); const b = document.querySelector('.blatt').cloneNode(true); const d = document.createElement('div'); d.className = 'druckbereich'; b.style.transform = 'none'; d.appendChild(b); document.body.appendChild(d); });
  await page.pdf({ path: out + '/test.pdf', format: 'A4', printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: 'screen' });
  await page.goto(`http://127.0.0.1:${port}/oenorm-a-1080-din-5008/`, { waitUntil: 'networkidle' });
  assert((await page.textContent('.wz-ausgabe')).includes('Passt'));
  await page.goto(`http://127.0.0.1:${port}/kuendigungsfristen-wohnung-vergleich/`, { waitUntil: 'networkidle' });
  await page.fill('#fv-zugang', '2026-11-05');
  const v = await page.textContent('.vergleich');
  assert(v.includes('28. Februar 2027') && v.includes('31. Dezember 2026') && v.includes('31. März 2027'), v);
  // VF01: CH ohne Ortsgebrauch ohne Mietbeginn – kein erfundener Beginn, keine Daten
  await page.selectOption('#fv-ch', 'mietdauer');
  await page.fill('#fv-zugang', '2026-11-03');
  await page.fill('#fv-beginn', '');
  let chKarte = await page.textContent('.vergleich .fristkarte:nth-child(3)');
  assert(chKarte.includes('Mietbeginn fehlt') && !/2027/.test(chKarte), 'CH ohne Mietbeginn: ' + chKarte);
  await page.fill('#fv-beginn', '2025-01-01');
  chKarte = await page.textContent('.vergleich .fristkarte:nth-child(3)');
  assert(chKarte.includes('31. März 2027') && !chKarte.includes('Mietbeginn fehlt'), chKarte);
  assert((await page.textContent('.wz-ausgabe')).includes('§ 573c Abs. 4 BGB'), 'Hinweis § 573c Abs. 4 BGB fehlt');
  // VF02: Frist im Schreiben folgt dem Datum des Schreibens
  await page.goto(`http://127.0.0.1:${port}/kaution-zurueckfordern/`, { waitUntil: 'networkidle' });
  await page.check('input[name=land][value=DE]');
  await page.fill('#b-kaution-datum', '2026-11-03');
  assert((await page.textContent('.blatt')).includes('bis 20. November 2026'), 'Kaution 3.11.');
  await page.fill('#b-kaution-datum', '2026-12-15');
  const kb = await page.textContent('.blatt');
  assert(kb.includes('bis 4. Januar 2027') && !kb.includes('20. November 2026'), 'Kaution 15.12.: ' + kb.slice(0, 600));
  await page.fill('#b-kaution-fristBis', '2026-12-01');
  assert((await page.textContent('.blatt')).includes('ENTWURF – nicht versandfertig'), 'Fristende vor Briefdatum nicht abgelehnt');
  // VF02: gespeicherter Entwurf wird beim Laden nicht still neu berechnet
  await page.evaluate(() => localStorage.setItem('vf24-entwurf-kaution', JSON.stringify({ land: 'DE', datum: '2026-11-03', fristTage: '14', postTage: '3', fristBis: '', __frist: { ende: '2026-11-23' } })));
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.inputValue('#b-kaution-datum'), '2026-11-03');
  assert.equal(await page.inputValue('#b-kaution-fristBis'), '2026-11-23');
  assert((await page.textContent('.fristkarte')).includes('Gespeicherte Frist beibehalten'), 'kein Hinweis beim Laden');
  assert.equal(JSON.parse(await page.evaluate(() => localStorage.getItem('vf24-entwurf-kaution'))).__frist.ende, '2026-11-23', 'Entwurf still überschrieben');
  await page.evaluate(() => localStorage.removeItem('vf24-entwurf-kaution'));
  // VF03: regionale Feiertage im Jahr des Fristendes; außerhalb der Abdeckung kein Datum
  await page.goto(`http://127.0.0.1:${port}/fristenrechner/`, { waitUntil: 'networkidle' });
  await page.check('input[name=land][value=DE]');
  await page.check('input[name=opt][value=allerheiligen]');
  await page.fill('#fr-ereignis', '2026-11-01');
  await page.fill('#fr-anzahl', '4');
  await page.selectOption('#fr-einheit', 'jahre');
  let fe = await page.textContent('.wz-ausgabe');
  assert(fe.includes('4. November 2030 (Montag)'), 'Allerheiligen 2030: ' + fe);
  await page.fill('#fr-anzahl', '20');
  fe = await page.textContent('.wz-ausgabe');
  assert(fe.includes('keine geprüften Feiertagsdaten') && !fe.includes('Letzter Tag der Frist'), '2046: ' + fe);
  const p2 = await browser.newPage();
  await p2.route(/feiertage\.json/, r => r.fulfill({ status: 404, body: 'nicht da' }));
  await p2.route(/googlesyndication|googletagmanager/, r => r.abort());
  await p2.goto(`http://127.0.0.1:${port}/fristenrechner/`, { waitUntil: 'networkidle' });
  await p2.check('input[name=land][value=DE]');
  await p2.fill('#fr-ereignis', '2026-03-20');
  fe = await p2.textContent('.wz-ausgabe');
  assert(fe.includes('Feiertagsdaten konnten nicht geladen werden') && !fe.includes('3. April 2026'), 'ohne Daten: ' + fe);
  await p2.close();
  // VF04: langer Brief wird mehrseitig gedruckt, nichts abgeschnitten
  await page.goto(`http://127.0.0.1:${port}/briefvorlage-leer/`, { waitUntil: 'networkidle' });
  const absatz = 'Dieser Absatz dient als Fülltext, damit der Brief über mehr als ein Blatt reicht und der Druck auf einer zweiten Seite weiterlaufen muss.';
  await page.fill('#b-leer-betreff', 'Langer Brief Druckprobe');
  await page.fill('#b-leer-inhalt', Array.from({ length: 24 }, (_, i) => (i + 1) + '. ' + absatz).join('\n\n') + '\n\nSCHLUSSMARKE Ende des Textes.');
  assert(await page.evaluate(() => document.querySelector('.blatt').classList.contains('zu-lang')), 'Überlauf nicht erkannt');
  await page.evaluate(() => { window.print = () => {}; });
  await page.click('text=Drucken oder als PDF sichern');
  await page.evaluate(() => document.body.classList.add('druck-brief'));
  await page.emulateMedia({ media: 'print' });
  const lang = out + '/test-lang.pdf';
  await page.pdf({ path: lang, format: 'A4', printBackground: true, preferCSSPageSize: true });
  await page.emulateMedia({ media: 'screen' });
  const seiten = require('child_process').execFileSync('pdftotext', ['-layout', lang, '-']).toString('utf8').split('\f').filter(t => t.trim());
  assert(seiten.length >= 2, 'nur ' + seiten.length + ' Seite(n)');
  assert(seiten[0].includes('Langer Brief Druckprobe') && seiten[0].includes('1. Dieser Absatz'), 'Seite 1 ohne Briefanfang');
  const rest = seiten.slice(1).join('\n');
  assert(rest.includes('SCHLUSSMARKE') && rest.includes('24. Dieser Absatz'), 'Seite 2 ohne Textende: ' + rest.slice(0, 300));
  const alles = seiten.join('\n');
  for (let i = 1; i <= 24; i++) assert(alles.includes(i + '. Dieser Absatz'), 'Absatz ' + i + ' fehlt im Druck');
  assert(!alles.includes('länger als eine Seite'), 'Überlaufhinweis im Druck');
  assert(!errs.length, errs.join('|'));
  console.log('Interaktionstest bestanden.');
  await browser.close(); srv.close();
})().catch(e => { console.error(e.message); process.exit(1); });
